local t = require("t")
local F = require("model.formats")

local function ok(format, line) return (F.validate_line(format, line)) end
local function bad(format, line)
  local r, key, vars = F.validate_line(format, line)
  t.eq(r, nil, format .. " " .. line)
  return key, vars
end

t.case("valid lines of every format (synthetic hex)", function()
  t.ok(ok("raw", "0212A4C8 7F"))
  t.ok(ok("raw", "0212a4c8 7f"))
  t.ok(ok("gsa", "0212A4C8 000F423F"))
  t.ok(ok("gsa", "0212A4C8000F"))
  t.ok(ok("ar_gba", "0212A4C8 000F423F"))
  t.ok(ok("ar_gba", "0212A4C8000F"))
  t.ok(ok("cb", "0212A4C8 000F"))
  t.ok(ok("ar_ds", "0212A4C8 000F423F"))
  t.ok(ok("gateway", "0212A4C8 000F423F"))
  t.ok(ok("game_genie", "00A-17B"))
  t.ok(ok("game_genie", "00A-17B-3C1"))
  t.ok(ok("game_genie", "00a-17b-3c1"))
end)

t.case("invalid lines give the right error", function()
  local key, vars = bad("gsa", "0212A4C 000F423F")
  t.eq(key, "err_digits_before"); t.eq(vars.n, 7); t.eq(vars.want, 8)
  key, vars = bad("gsa", "0212A4C8 000F423")
  t.eq(key, "err_digits_after"); t.eq(vars.n, 7)
  key, vars = bad("gsa", "0212A4C8 000G423F")
  t.eq(key, "err_not_hex"); t.eq(vars.char, "G")
  key = bad("cb", "0212A4C8 000F423F")
  t.eq(key, "err_digits_after")
  key = bad("raw", "0212A4C8 7")
  t.eq(key, "err_digits_after")
  key = bad("ar_ds", "0212A4C8")
  t.eq(key, "err_one_group")
  key = bad("gateway", "0212A4C8 000F423F 11")
  t.eq(key, "err_group_count")
  key, vars = bad("game_genie", "00A-17")
  t.eq(key, "err_gg_group"); t.eq(vars.pos, 2)
  key = bad("game_genie", "00A 17B")
  t.eq(key, "err_shape")
  key, vars = bad("game_genie", "00A-17B-3C")
  t.eq(key, "err_gg_group"); t.eq(vars.pos, 3)
  key = bad("gsa", "")
  t.eq(key, "err_empty")
  bad("nope", "0212A4C8 000F423F")
end)

t.case("detection prefers the formats of the system", function()
  t.eq(F.detect("0212A4C8 000F423F", "gba"), "gsa")
  t.eq(F.detect("0212A4C8 000F423F", "nds"), "ar_ds")
  t.eq(F.detect("0212A4C8 000F423F", "3ds"), "gateway")
  t.eq(F.detect("0212A4C8 000F", "gba"), "cb")
  t.eq(F.detect("0212A4C8 7F", "gba"), "raw")
  t.eq(F.detect("00A-17B-3C1", "gb"), "game_genie")
  t.eq(F.detect("0212A4C8 000F423F\n0212A4CC 00000001", "gba"), "gsa")
  t.eq(F.detect("0212A4C8 000F423F\n0212A4CC 000F", "gba"), nil)
  t.eq(F.detect("", "gba"), nil)
  t.eq(F.detect("hello", "gba"), nil)
  -- a code for another system still gets a format
  t.eq(F.detect("00A-17B", "gba"), "game_genie")
end)

t.case("candidates list every matching format", function()
  t.eq(F.candidates("0212A4C8 000F423F", "gba"), { "gsa", "ar_gba", "ar_ds", "gateway" })
end)

t.case("check normalizes lines and reports line numbers", function()
  local r = F.check("0212a4c8   000f423f\n\n0212A4CC 00000001", "gsa", "gba")
  t.eq(r.errors, {})
  t.eq(r.lines, { "0212A4C8 000F423F", "0212A4CC 00000001" })
  t.eq(r.count, 2)
  r = F.check("0212A4C8 000F423F\n0212A4C 000F423F\n0212A4CC 000G423F", "gsa", "gba")
  t.eq(#r.errors, 2)
  t.eq(r.errors[1].n, 2); t.eq(r.errors[1].key, "err_digits_before")
  t.eq(r.errors[2].n, 3); t.eq(r.errors[2].key, "err_not_hex")
end)

t.case("check suggests the format the lines look like", function()
  local r = F.check("0212A4C8 000F", "gsa", "gba")
  t.eq(#r.errors, 1)
  t.eq(r.other, "cb")
  r = F.check("0212A4C8 000F", "cb", "gba")
  t.eq(r.errors, {})
  t.eq(r.other, nil)
end)

t.case("Game Genie lines are normalized with dashes", function()
  local r = F.check("00a 17b 3c1", "game_genie", "gb")
  t.eq(#r.errors, 1) -- spaces are not allowed
  r = F.check("00a-17b-3c1", "game_genie", "gb")
  t.eq(r.lines, { "00A-17B-3C1" })
end)

t.case("a cheat has at most 64 lines", function()
  local lines = {}
  for i = 1, 65 do lines[i] = string.format("0212A4C8 %08X", i) end
  local r = F.check(table.concat(lines, "\n"), "gsa", "gba")
  t.eq(r.errors[1].key, "err_too_many_lines")
end)

t.case("tags and system lists", function()
  t.eq(F.tags.ar_ds, "AR DS"); t.eq(F.tags.gateway, "GATEWAY"); t.eq(F.tags.game_genie, "GG")
  t.eq(F.for_system("3DS"), { "gateway", "raw" })
  t.eq(#F.for_system("xyz"), 7)
  t.ok(F.known("gsa")); t.ok(not F.known("nope")); t.ok(not F.known(nil))
end)
