t.case("store conflict: another device's cheats are kept", function()
  local m, app = H.boot(nil, { { name = "Infinite Boost" } })
  m.store_external("cheats.axve", { v = 1, deleted = {}, cheats = {
    { id = "e1", name = "Infinite Boost", format = "gsa", code = GSA, group = "mine", enabled = false },
    { id = "r1", name = "Remote Cheat", format = "gsa", code = GSA2, group = "imported", enabled = false } } })
  m.action("toggle:e1", true, "panel")
  t.eq(#stored(m).cheats, 2)
  t.ok(H.has_text(H.panel(m), "Remote Cheat"))
  t.eq(stored(m).cheats[1].enabled, true)
  t.ok(not H.has_text(H.panel(m), "could not be saved"))
end)

