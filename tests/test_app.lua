  m.action("toggle:e1", true, "panel")
  t.eq(#m.cheats.apply_calls, 1)
  m.run_current.rules.cheats = "off"
  m.tick(120)
  t.ok(V.find(H.panel(m), "blocked"))
  t.eq(m.cheats.clears, 1)
end)

