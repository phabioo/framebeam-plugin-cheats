t.case("toggle on applies the full list, toasts, and turn off from the toast", function()
  local m = H.boot(nil, { { name = "Infinite Boost" }, { name = "Lumen Walk", code = GSA2 } })
  t.ok(H.has_text(H.panel(m), "0 ON"))
  m.action("toggle:e1", true, "panel")
  t.eq(#m.cheats.apply_calls, 1)
  t.eq(m.cheats.apply_calls[1], { { id = "e1", name = "Infinite Boost", format = "gsa", code = GSA, enabled = true } })
  t.eq(stored(m).cheats[1].enabled, true)
  t.ok(H.has_text(H.panel(m), "1 ON"))
  t.eq(#m.notes, 1)
  t.eq(m.notes[1].text, "Infinite Boost is on")
  t.eq(m.notes[1].actions[1].label, "Turn off")
  m.action("toggle:e2", true, "panel")
  t.eq(#m.cheats.apply_calls[2], 2, "the full list of enabled cheats is sent")
  m.action(m.notes[1].actions[1].action, m.notes[1].actions[1].value, "toast")
  t.eq(#m.cheats.apply_calls[3], 1)
  t.eq(m.cheats.apply_calls[3][1].id, "e2")
  t.eq(stored(m).cheats[1].enabled, false)
  t.ok(H.has_text(H.panel(m), "1 ON"))
end)

