t.case("run rule: event cheats.blocked dims the list and turns cheats off", function()
  local m = H.boot(nil, { { name = "Infinite Boost", enabled = true }, { name = "Lumen Walk", code = GSA2 } })
  m.fire_event("app", "cheats.blocked", { reason = "run_rule" })
  local p = H.panel(m)
  t.ok(V.find(p, "blocked"))
  t.ok(H.has_text(p, "Cheats are off in this run"))
  t.ok(H.has_text(p, "OFF IN THIS RUN"))
  t.eq(#H.toggles(p), 0)
  t.eq(m.cheats.clears, 1)
  t.eq(stored(m).cheats[1].enabled, false)
  m.action("toggle:e2", true, "panel")
  t.eq(stored(m).cheats[2].enabled, false, "no toggling while blocked")
  m.action("recheck", nil, "panel")
  t.ok(not V.find(H.panel(m), "blocked"))
  t.eq(#H.toggles(H.panel(m)), 2)
end)

t.case("run rule: fb.run rules.cheats == off at start, and live changes", function()
  local m = H.boot({ run = { id = "r1", rules = { cheats = "off" } } }, { { name = "Infinite Boost", enabled = true } })
  t.ok(V.find(H.panel(m), "blocked"))
  t.eq(#m.cheats.apply_calls, 0)
  t.eq(stored(m).cheats[1].enabled, false)
