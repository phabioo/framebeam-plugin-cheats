local t = require("t")
local H = require("app")
local V = H.V

local GSA, GSA2 = "0212A4C8 000F423F", "0212A4CC 00000001"

local function stored(m) return m.store.data["cheats.axve"] and m.store.data["cheats.axve"].value end

t.case("empty list shows the empty state with both buttons", function()
  local m = H.boot()
  local p = H.panel(m)
  t.ok(V.find(p, "empty_none"))
  t.ok(H.has_text(p, "No cheats for Lumen Drift yet"))
  t.ok(V.find(p, "btn_add") and V.find(p, "btn_db"))
  t.ok(H.has_text(p, "0 ON"))
  t.eq(#m.cheats.apply_calls, 0, "nothing applied for an empty list")
  t.ok(H.screen(m), "screen has a landing tree")
end)

t.case("add a cheat: dialog opens, form validates, cheat lands in Mine", function()
  local m = H.boot()
  m.action("add", nil, "panel")
  t.eq(m.opened, { "screen" })
  local s = H.screen(m)
  t.ok(V.find(s, "ta_name") and V.find(s, "ta_code") and V.find(s, "sel_fmt"))
  t.ok(V.find(s, "not_ready"), "no Add button yet")
  t.ok(not V.find(s, "btn_confirm"))
  H.type_code(m, "Infinite Boost", GSA .. "\n" .. GSA2)
  s = H.screen(m)
  t.ok(H.has_text(s, "Found: GSA"))
  t.ok(H.has_text(s, "2 lines · GameShark (GSA)"))
  t.ok(V.find(s, "btn_confirm"))
  m.action("confirm_add", nil, "screen")
  local saved = stored(m)
  t.eq(#saved.cheats, 1)
  t.eq(saved.cheats[1].name, "Infinite Boost")
  t.eq(saved.cheats[1].format, "gsa")
  t.eq(saved.cheats[1].code, GSA .. "\n" .. GSA2)
  t.eq(saved.cheats[1].group, "mine")
  t.eq(saved.cheats[1].enabled, false)
  t.ok(H.has_text(H.screen(m), "was added to Mine"))
  t.ok(H.has_text(H.panel(m), "Mine · 1"))
  t.eq(#m.cheats.apply_calls, 0, "adding does not turn it on")
  m.action("dlg_again", nil, "screen")
  t.ok(V.find(H.screen(m), "ta_code"))
  m.action("dlg_close", nil, "screen")
  t.eq(m.closed, 1)
end)

