t.case("edit mode: edit a cheat, remove a cheat", function()
  local m = H.boot(nil, { { name = "Infinite Boost", enabled = true }, { name = "Lumen Walk", code = GSA2 } })
  m.action("edit_mode", nil, "panel")
  local p = H.panel(m)
  t.eq(#H.toggles(p), 0)
  local rm = V.all(p, "button")
  local found
  for _, b in ipairs(rm) do if b.action == "remove:e2" then found = b end end
  t.ok(found and found.confirm and found.confirm.danger)
  m.action("edit:e1", nil, "panel")
  local s = H.screen(m)
  t.eq(V.find(s, "ta_name").value, "Infinite Boost")
  t.eq(V.find(s, "ta_code").value, GSA)
  t.ok(H.has_text(s, "Edit cheat in Lumen Drift"))
  t.ok(not V.find(s, "dlg_tabs"))
  m.action("ta_name", "Infinite Boost+", "screen")
  m.action("ta_code", "0212A4C8 000F4240", "screen")
  m.action("confirm_add", nil, "screen")
  t.eq(stored(m).cheats[1].name, "Infinite Boost+")
  t.eq(stored(m).cheats[1].code, "0212A4C8 000F4240")
  t.eq(m.cheats.apply_calls[#m.cheats.apply_calls][1].code, "0212A4C8 000F4240", "an enabled cheat is applied again")
  m.action("remove:e1", nil, "panel")
  t.eq(#stored(m).cheats, 1)
  t.eq(stored(m).deleted, { e1 = true })
  t.eq(#m.cheats.apply_calls[#m.cheats.apply_calls], 0, "the removed cheat leaves the core")
end)

